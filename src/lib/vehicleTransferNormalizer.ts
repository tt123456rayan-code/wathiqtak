export function normalizeVehicleTransferText(text: string) {
  return text
    .replace(/\s+/g, " ")
    .replace(/الاردث|الاردنيه|الأردنيه/g, "الأردنية")
    .replace(/هوية\s*\.?\s*Wal|هوية احوال|هويه احوال|هوية الأحوال/g, "هوية أحوال")
    .replace(/العاصمه/g, "العاصمة")
    .replace(/رقم\s*الباتف|رقم\s*الهاتف/g, "رقم الهاتف")
    .replace(/اسم\s*المشترى/g, "اسم المشتري")
    .replace(/ادارة ترخيص السواقين والمركبات/g, "إدارة ترخيص السواقين والمركبات")
    .replace(/نموذج\s*نقل\s*مركبه/g, "نموذج نقل مركبة")
    .replace(/رقم\s*القيد\s*المدني/g, "الرقم الوطني")
    .replace(/الرقم\s*الوطنى/g, "الرقم الوطني")
    .replace(/خصوصى/g, "خصوصي")
    .trim();
}
